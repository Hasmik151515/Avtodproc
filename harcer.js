window.AVTODPROC_STATE_KEY = 'avtodprocProgressState';

function readStoredAppState() {
    try {
        const raw = localStorage.getItem(window.AVTODPROC_STATE_KEY);
        return raw ? JSON.parse(raw) : {};
    } catch (error) {
        console.warn('Could not read saved app state:', error);
        return {};
    }
}

function writeStoredAppState(state) {
    try {
        localStorage.setItem(window.AVTODPROC_STATE_KEY, JSON.stringify(state));
    } catch (error) {
        console.warn('Could not save app state:', error);
    }
}

function persistNavigationState() {
    const state = readStoredAppState();
    const activeSection = document.querySelector('.tab-section:not(.hidden)');
    state.activeTab = activeSection ? activeSection.id.replace('section-', '') : 'home';
    writeStoredAppState(state);
}

function restoreNavigationState() {
    const savedState = readStoredAppState();
    if (!savedState.activeTab) return false;
    const targetSection = document.getElementById('section-' + savedState.activeTab);
    if (!targetSection) return false;
    if (typeof switchTab === 'function') {
        switchTab(savedState.activeTab === 'pricing' ? 'home' : savedState.activeTab);
        return true;
    }
    return false;
}

function persistThematicProgress() {
    const state = readStoredAppState();
    state.thematic = {
        active: !!(document.getElementById('thematic-practice-view') && !document.getElementById('thematic-practice-view').classList.contains('hidden')),
        groupId: currentThematicGroupId,
        currentQuestionIndex: thematicCurrIdx,
        userAnswers: thematicUserAnswersRecord,
        correctAnswers: thematicCorrectAnswers,
        wrongAnswers: thematicWrongAnswers,
        timeRemainingSeconds: thematicTimeRemaining
    };
    writeStoredAppState(state);
}

