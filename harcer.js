function renderThematicQuestion() {
    const q = thematicQuestionsList[thematicCurrIdx];
    document.getElementById('thematic-progress-indicator').innerText = `Հարց ${thematicCurrIdx + 1} / ${thematicQuestionsList.length}`;
    document.getElementById('thematic-q-text').innerText = q.q;
    document.getElementById('thematic-feedback').classList.add('hidden');
    persistThematicProgress();

    const imgBox = document.getElementById('thematic-img-box');
    const imgTag = document.getElementById('thematic-img');
    if (q.image && q.image.trim() !== "") {
        imgTag.src = q.image;
        if (imgBox) imgBox.classList.remove('hidden');
    } else {
        if (imgBox) imgBox.classList.add('hidden');
    }

    const container = document.getElementById('thematic-options-container');
    container.innerHTML = '';

    const alreadyAnswered = thematicUserAnswersRecord[thematicCurrIdx] !== undefined;

    q.options.forEach((optText, optIdx) => {
        const btn = document.createElement('button');

        let btnClasses = "w-full text-left p-4 rounded-2xl border transition flex items-center space-x-4 ";
        if (alreadyAnswered) {
            btn.disabled = true;
            if (optIdx === q.correct) {
                btnClasses += "bg-neon-500/20 border-neon-400 text-neon-400 font-bold";
            } else if (optIdx === thematicUserAnswersRecord[thematicCurrIdx] && optIdx !== q.correct) {
                btnClasses += "bg-red-500/20 border-red-400 text-red-300";
            } else {
                btnClasses += "bg-black/20 border-gray-900 text-gray-600 opacity-50";
            }
        } else {
            btnClasses += "bg-black/40 border-gray-800 text-gray-300 hover:border-neon-500/40";
        }

        btn.className = btnClasses;
        btn.innerHTML = `
                    <div class="w-8 h-8 rounded-xl bg-gray-800 text-gray-300 flex items-center justify-center font-bold text-sm shrink-0">${String.fromCharCode(65 + optIdx)}</div>
                    <span class="flex-grow text-sm font-medium">${optText}</span>
                `;

        if (!alreadyAnswered) {
            btn.onclick = () => selectThematicAnswer(optIdx);
        }
        container.appendChild(btn);
    });

    if (alreadyAnswered) {
        const feedbackBox = document.getElementById('thematic-feedback');
        feedbackBox.classList.remove('hidden');
        const userAns = thematicUserAnswersRecord[thematicCurrIdx];
        if (userAns === q.correct) {
            feedbackBox.className = "p-4 rounded-xl bg-neon-500/10 border border-neon-500/30 text-neon-400 text-sm font-semibold";
            feedbackBox.innerText = "✓ Ճիշտ է:";
        } else {
            feedbackBox.className = "p-4 rounded-xl bg-red-500/10 border border-red-500/30 text-red-400 text-sm font-semibold";
            feedbackBox.innerText = `✕ Սխալ է: Ճիշտ պատասխանն էր՝ ${String.fromCharCode(65 + q.correct)}. ${q.options[q.correct]}`;
        }
    }

    document.getElementById('thematic-prev-btn').disabled = thematicCurrIdx === 0;

    const nextBtn = document.getElementById('thematic-next-btn');
    if (thematicCurrIdx === thematicQuestionsList.length - 1) {
        nextBtn.textContent = 'Ավարտել թեստը ✓';
    } else {
        nextBtn.textContent = 'Հաջորդը →';
    }
}

function selectThematicAnswer(selectedIdx) {
    const q = thematicQuestionsList[thematicCurrIdx];
    thematicUserAnswersRecord[thematicCurrIdx] = selectedIdx;
    persistThematicProgress();

    const feedbackBox = document.getElementById('thematic-feedback');
    feedbackBox.classList.remove('hidden');

    if (selectedIdx === q.correct) {
        thematicCorrectAnswers++;
        feedbackBox.className = "p-4 rounded-xl bg-neon-500/10 border border-neon-500/30 text-neon-400 text-sm font-semibold";
        feedbackBox.innerText = "✓ Ճիշտ է:";
    } else {
        thematicWrongAnswers++;
        feedbackBox.className = "p-4 rounded-xl bg-red-500/10 border border-red-500/30 text-red-400 text-sm font-semibold";
        feedbackBox.innerText = `✕ Սխալ է: Ճիշտ պատասխանն էր՝ ${String.fromCharCode(65 + q.correct)}. ${q.options[q.correct]}`;
    }

    const allButtons = document.querySelectorAll('#thematic-options-container button');
    allButtons.forEach((b, idx) => {
        b.disabled = true;
        if (idx === q.correct) {
            b.className = "w-full text-left p-4 rounded-2xl bg-neon-500/20 border border-neon-400 text-neon-400 font-bold flex items-center space-x-4";
        } else if (idx === selectedIdx && selectedIdx !== q.correct) {
            b.className = "w-full text-left p-4 rounded-2xl bg-red-500/20 border border-red-400 text-red-300 flex items-center space-x-4";
        } else {
            b.className = "w-full text-left p-4 rounded-2xl bg-black/20 border border-gray-900 text-gray-600 flex items-center space-x-4 opacity-50";
        }
    });
}

function nextThematicQuestion() {
    if (thematicUserAnswersRecord[thematicCurrIdx] === undefined) {
        alert("Խնդրում ենք ընտրել պատասխան նախքան հաջորդ հարցին անցնելը:");
        return;
    }

    if (thematicCurrIdx < thematicQuestionsList.length - 1) {
        thematicCurrIdx++;
        renderThematicQuestion();
    } else {
        showThematicResults();
    }
}

function showThematicResults() {
    if (thematicTimerInterval) clearInterval(thematicTimerInterval);
    const state = readStoredAppState();
    if (state.thematic) {
        state.thematic.active = false;
        writeStoredAppState(state);
    }
    document.getElementById('thematic-practice-view').classList.add('hidden');
    document.getElementById('thematic-results-view').classList.remove('hidden');

    document.getElementById('res-correct-count').innerText = thematicCorrectAnswers;
    document.getElementById('res-wrong-count').innerText = thematicWrongAnswers;
}

function prevThematicQuestion() {
    if (thematicCurrIdx > 0) {
        thematicCurrIdx--;
        renderThematicQuestion();
    }
}

