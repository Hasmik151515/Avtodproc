function startThematicTimer() {
    if (thematicTimerInterval) clearInterval(thematicTimerInterval);

    updateTimerDisplay();
    thematicTimerInterval = setInterval(() => {
        thematicTimeRemaining--;
        updateTimerDisplay();
        persistThematicProgress();

        if (thematicTimeRemaining <= 0) {
            clearInterval(thematicTimerInterval);
            alert("Ժամանակն ավարտվեց:");
            showThematicResults();
        }
    }, 1000);
}

function updateTimerDisplay() {
    const minutes = Math.floor(thematicTimeRemaining / 60);
    const seconds = thematicTimeRemaining % 60;
    const timerElement = document.getElementById('thematic-timer-display');
    if (timerElement) {
        timerElement.innerText = `${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}`;
    }
}

