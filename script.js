let activeSignCategory = 'all';

function initRoadSigns(filter = activeSignCategory, searchQuery = '') {
    const grid = document.getElementById('signs-grid');
    const query = searchQuery.trim().toLocaleLowerCase('hy-AM');
    const filtered = roadSignsData.filter(sign => {
        const matchesCategory = filter === 'all' || sign.cat === filter;
        const matchesQuery = !query || `${sign.code} ${sign.title} ${sign.categoryTitle}`.toLocaleLowerCase('hy-AM').includes(query);
        return matchesCategory && matchesQuery;
    });

    grid.innerHTML = '';
    document.getElementById('signs-count').textContent = `${filtered.length} նշան`;
    if (filtered.length === 0) {
        const empty = document.createElement('div');
        empty.className = 'col-span-full rounded-2xl border border-gray-800 bg-cardBg p-10 text-center text-sm text-gray-400';
        empty.textContent = 'Այս որոնմամբ նշան չի գտնվել։';
        grid.appendChild(empty);
        return;
    }

    filtered.forEach(sign => {
        const card = document.createElement('article');
        card.className = 'group rounded-2xl border border-gray-800 bg-cardBg p-3 sm:p-4 shadow-lg transition duration-200 hover:-translate-y-1 hover:border-neon-500/50 hover:shadow-neon-500/5';

        const heading = document.createElement('div');
        heading.className = 'flex items-center justify-between gap-2';
        const code = document.createElement('span');
        code.className = 'rounded-lg bg-neon-500/10 px-2.5 py-1 font-mono text-xs font-extrabold text-neon-400';
        code.textContent = sign.code;
        const category = document.createElement('span');
        category.className = 'truncate text-[10px] text-gray-500';
        category.textContent = sign.categoryTitle;
        heading.append(code, category);

        const imageBox = document.createElement('div');
        imageBox.className = 'relative my-3 flex h-28 items-center justify-center overflow-hidden rounded-xl border border-white/5 bg-gradient-to-br from-white to-gray-100 sm:h-32';
        const fallback = document.createElement('span');
        fallback.className = 'hidden font-mono text-xl font-black text-gray-500';
        fallback.textContent = sign.code;
        const image = document.createElement('img');
        image.className = 'h-full w-full object-contain p-2 transition duration-200 group-hover:scale-105';
        image.src = sign.image;
        image.alt = `${sign.title} (${sign.code})`;
        image.loading = 'lazy';
        image.decoding = 'async';
        image.addEventListener('error', () => {
            image.classList.add('hidden');
            fallback.classList.remove('hidden');
        }, { once: true });
        imageBox.append(image, fallback);

        const title = document.createElement('h3');
        title.className = 'min-h-10 text-center text-xs font-bold leading-relaxed text-gray-200 sm:text-sm';
        title.textContent = sign.title;
        card.append(heading, imageBox, title);
        grid.appendChild(card);
    });
}

function filterSignCategory(category) {
    activeSignCategory = category;
    document.querySelectorAll('.sign-cat-btn').forEach(button => {
        const selected = button.dataset.category === category;
        button.className = selected
            ? 'sign-cat-btn rounded-xl bg-neon-500 px-4 py-2 text-xs font-bold text-black transition'
            : 'sign-cat-btn rounded-xl border border-gray-800 bg-cardBg px-4 py-2 text-xs font-bold text-gray-300 transition hover:border-neon-500/40';
    });
    filterSigns();
}

function filterSigns() {
    initRoadSigns(activeSignCategory, document.getElementById('sign-search-input').value);
}

