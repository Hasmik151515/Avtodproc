function toggleAccountMenu(event) {
    event.stopPropagation();
    const dropdown = document.getElementById('auth-account-dropdown');
    const toggle = document.getElementById('auth-account-toggle');
    if (!dropdown || !toggle) return;
    const isOpening = dropdown.classList.contains('hidden');
    dropdown.classList.toggle('hidden', !isOpening);
    toggle.setAttribute('aria-expanded', String(isOpening));
}

function closeAccountMenu() {
    const dropdown = document.getElementById('auth-account-dropdown');
    const toggle = document.getElementById('auth-account-toggle');
    if (dropdown) dropdown.classList.add('hidden');
    if (toggle) toggle.setAttribute('aria-expanded', 'false');
}

document.addEventListener('click', event => {
    const menu = document.getElementById('auth-account-menu');
    if (menu && !menu.contains(event.target)) closeAccountMenu();
});

function switchTab(tabId) {
    const targetTabId = tabId === 'pricing' ? 'home' : tabId;
    const currentSection = document.querySelector('.tab-section:not(.hidden)');
    if (currentSection && currentSection.id === 'section-tests' && targetTabId !== 'tests' &&
        typeof exitActiveTestForNavigation === 'function') {
        exitActiveTestForNavigation();
    }

    document.querySelectorAll('.tab-section').forEach(sec => sec.classList.add('hidden'));
    document.getElementById('section-' + targetTabId).classList.remove('hidden');

    document.querySelectorAll('.nav-btn').forEach(btn => {
        btn.classList.remove('text-neon-400', 'bg-neon-500/10', 'border', 'border-neon-500/30');
        btn.classList.add('text-gray-300');
    });
    const activeBtn = document.getElementById('nav-' + tabId);
    if (activeBtn) {
        activeBtn.classList.remove('text-gray-300');
        activeBtn.classList.add('text-neon-400', 'bg-neon-500/10', 'border', 'border-neon-500/30');
    }
    if (typeof persistNavigationState === 'function') {
        persistNavigationState();
    }
    if (tabId === 'pricing') {
        window.requestAnimationFrame(() => {
            document.getElementById('section-pricing').scrollIntoView({ behavior: 'smooth', block: 'start' });
        });
    } else {
        window.scrollTo({ top: 0, behavior: 'smooth' });
    }
}

function toggleMobileMenu() {
    document.getElementById('mobile-menu').classList.toggle('hidden');
}

function showToast(title, message, isSuccess = true) {
    const toast = document.getElementById('toast-box');
    if (!toast) return;
    document.getElementById('toast-title').innerText = title;
    document.getElementById('toast-message').innerText = message;
    document.getElementById('toast-icon').innerText = isSuccess ? '✓' : '⚠️';
    toast.classList.remove('hidden');
    setTimeout(() => { toast.classList.add('hidden'); }, 4000);
}



