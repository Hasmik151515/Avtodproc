function initColorTestPicker() {
    const picker = document.getElementById("color-test-picker");
    picker.innerHTML = "";
    colorTests.forEach((test, index) => {
        const card = document.createElement("button");
        card.type = "button";
        card.className = "rounded-2xl border border-neon-500/30 bg-black/30 p-6 text-left transition hover:border-neon-400 hover:bg-neon-500/10" + (index === 6 ? " col-span-2" : "");
        card.innerHTML = '<span class="block text-lg font-bold text-white">' + test.title + '</span><span class="mt-2 block text-sm text-gray-400">10 հարց</span>';
        card.onclick = () => startColorTest(index);
        picker.appendChild(card);
    });
}

function startColorTest(index) {
    activeColorTestIndex = index;
    currentColorIndex = 0;
    colorCorrectAnswers = 0;
    colorWrongAnswers = 0;
    document.getElementById("color-test-picker").classList.add("hidden");
    document.getElementById("color-test-player").classList.remove("hidden");
    document.getElementById("color-test-results").classList.add("hidden");
    document.getElementById("color-plate-frame").classList.remove("hidden");
    document.getElementById("color-options-grid").classList.remove("hidden");
    renderColorTestPlate();
}

function showColorTestPicker() {
    document.getElementById("color-test-player").classList.add("hidden");
    document.getElementById("color-test-picker").classList.remove("hidden");
    document.getElementById("color-test-results").classList.add("hidden");
    document.getElementById("restart-color-test-btn").classList.add("hidden");
}

function renderColorTestPlate() {
    const colorPerceptionQuestions = colorTests[activeColorTestIndex].questions;
    const question = colorPerceptionQuestions[currentColorIndex];
    document.getElementById('color-plate-frame').classList.remove('hidden');
    document.getElementById('color-options-grid').classList.remove('hidden');
    document.getElementById('color-question-progress').innerText =
        `Հարց ${currentColorIndex + 1} / ${colorPerceptionQuestions.length}`;
    document.getElementById('color-question-text').innerText = question.q;
    const image = document.getElementById('color-question-image');
    const placeholder = document.getElementById('color-image-placeholder');
    image.classList.add('hidden');
    placeholder.classList.remove('hidden');
    document.getElementById('color-image-path').innerText = question.image;
    image.onload = () => {
        image.classList.remove('hidden');
        placeholder.classList.add('hidden');
    };
    image.onerror = () => {
        image.classList.add('hidden');
        placeholder.classList.remove('hidden');
    };
    if (question.image) {
        image.src = question.image;
    } else {
        image.removeAttribute('src');
    }

    const grid = document.getElementById('color-options-grid');
    grid.innerHTML = '';
    document.getElementById('color-feedback').innerText = '';
    document.getElementById('color-feedback').className = 'text-sm font-semibold min-h-[24px] pt-2';
    document.getElementById('color-test-results').classList.add('hidden');
    document.getElementById('next-color-btn').classList.add('hidden');
    document.getElementById('restart-color-test-btn').classList.add('hidden');

    question.options.forEach((option, optionIndex) => {
        const btn = document.createElement('button');
        btn.className = "p-4 rounded-2xl bg-black/50 border border-gray-700 text-white font-mono text-lg font-bold hover:border-neon-400 hover:bg-neon-500/10 transition shadow";
        btn.innerText = option;
        btn.onclick = () => submitColorAnswer(optionIndex, question.correct, btn);
        grid.appendChild(btn);
    });
}

function submitColorAnswer(selectedIndex, correctIndex, btnElement) {
    const colorPerceptionQuestions = colorTests[activeColorTestIndex].questions;
    const feedback = document.getElementById('color-feedback');
    const allBtns = document.querySelectorAll('#color-options-grid button');
    const question = colorPerceptionQuestions[currentColorIndex];

    allBtns.forEach(b => b.disabled = true);

    if (selectedIndex === correctIndex) {
        colorCorrectAnswers++;
        btnElement.className = "p-4 rounded-2xl bg-neon-500/20 border border-neon-400 text-neon-400 font-mono text-lg font-bold shadow-lg";
        feedback.innerText = "✓ Շատ լավ է: Ճիշտ պատասխան:";
        feedback.className = "text-sm font-semibold text-neon-400 pt-2";
    } else {
        colorWrongAnswers++;
        btnElement.className = "p-4 rounded-2xl bg-red-500/20 border border-red-400 text-red-300 font-mono text-lg font-bold shadow-lg";
        const correctButton = allBtns[correctIndex];
        correctButton.className = "p-4 rounded-2xl bg-neon-500/20 border border-neon-400 text-neon-400 font-mono text-lg font-bold shadow-lg";
        feedback.innerText = `✕ Սխալ պատասխան: Ճիշտ թիվն էր՝ ${question.options[correctIndex]}`;
        feedback.className = "text-sm font-semibold text-red-400 pt-2";
    }

    const nextButton = document.getElementById('next-color-btn');
    nextButton.innerText = currentColorIndex === colorPerceptionQuestions.length - 1
        ? 'Ավարտել թեստը ✓'
        : 'Հաջորդ հարցը →';
    nextButton.classList.remove('hidden');
}

function nextColorPlate() {
    const colorPerceptionQuestions = colorTests[activeColorTestIndex].questions;
    if (currentColorIndex < colorPerceptionQuestions.length - 1) {
        currentColorIndex++;
        renderColorTestPlate();
        return;
    }

    document.getElementById('color-plate-frame').classList.add('hidden');
    document.getElementById('color-question-image').removeAttribute('src');
    document.getElementById('color-options-grid').classList.add('hidden');
    document.getElementById('color-question-progress').innerText =
        `Ավարտված է՝ ${colorPerceptionQuestions.length} հարց`;
    document.getElementById('color-question-text').innerText =
        'Շնորհավորում ենք, ավարտեցիք գունընկալման թեստը:';
    document.getElementById('color-feedback').innerText =
        'Այս թեստը ուսումնական նպատակով է և չի փոխարինում մասնագիտական բժշկական հետազոտությանը։';
    document.getElementById('color-feedback').className =
        'text-sm font-semibold min-h-[24px] pt-2 text-gray-400';
    showColorTestResults();
    document.getElementById('next-color-btn').classList.add('hidden');
    document.getElementById('restart-color-test-btn').classList.remove('hidden');
}

function showColorTestResults() {
    const colorPerceptionQuestions = colorTests[activeColorTestIndex].questions;
    const totalQuestions = colorPerceptionQuestions.length;
    const percentage = Math.round((colorCorrectAnswers / totalQuestions) * 100);
    document.getElementById('color-result-correct').innerText = colorCorrectAnswers;
    document.getElementById('color-result-wrong').innerText = colorWrongAnswers;
    document.getElementById('color-result-percentage').innerText = `${percentage}%`;
    const progress = document.getElementById('color-result-progress');
    progress.style.width = `${percentage}%`;
    progress.parentElement.setAttribute('aria-valuenow', String(percentage));
    document.getElementById('color-test-results').classList.remove('hidden');
}

